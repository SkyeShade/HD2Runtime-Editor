"""Your own pictures as preset icons (a local, opt-in build step, like tools/mod_icons.py).

    py tools/preset_icons.py                 # every PNG/JPG in Documents\\HD2R Editor\\Preset icons, then build normally
    py tools/preset_icons.py FOLDER          # every picture in FOLDER
    py tools/preset_icons.py --clean         # remove them again

Why a build step: HD2Runtime draws only images a mod's build compiled into its archive (docs/custom-images.md in the
Runtime: "The Runtime never creates engine resources"), so the editor cannot load a picture file while the game runs.
This tool turns each picture into the editor's own images the way tools/mod_icons.py does (its own most common colours
as three stacked mask layers) and lists them in src/editor/generated/preset_icons.lua; the next build packs them in.
In the game, a preset's ICON picker then offers them under their file names.

Writes images/pi_<slug>_<layer>.png and src/editor/generated/preset_icons.lua:
    return {icons = {{name = 'My Icon', layers = {{image, colours = {r, g, b}}}}}}
The pictures are yours: they are git-ignored and end up only in builds you make yourself.
"""
import argparse
import hashlib
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mod_icons import layers_of, lua_string  # noqa: E402

PROJECT = Path(__file__).resolve().parents[1]
PREFIX = 'pi_'
TYPES = ('.png', '.jpg', '.jpeg')
MAX_NAME = 40


def default_folder():
    return Path(os.environ.get('USERPROFILE', '')) / 'Documents' / 'HD2R Editor' / 'Preset icons'


def clean(images, generated, quiet=False):
    n = 0
    for p in images.glob(PREFIX + '*.png'):
        p.unlink()
        n += 1
    if generated.is_file():
        generated.unlink()
    if not quiet:
        print('removed %d preset picture images' % n)


def slug_of(name):
    """A short image id for a picture's name: letters and digits, then a hash so two names never collide."""
    base = re.sub(r'[^a-z0-9]+', '', name.lower())[:12] or 'icon'
    return base + hashlib.sha256(name.encode('utf-8')).hexdigest()[:6]


def build(folder, images, generated):
    pictures = sorted(p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in TYPES)
    clean(images, generated, quiet=True)
    images.mkdir(exist_ok=True)
    entries, skipped = [], []
    for path in pictures:
        name = path.stem.strip()[:MAX_NAME]
        layers = layers_of(path) if name else None
        if not layers:
            skipped.append(path.name)
            continue
        slug = slug_of(name)
        items = []
        for n, (image, cols) in enumerate(layers, 1):
            iid = '%s%s_%d' % (PREFIX, slug, n)
            image.save(images / (iid + '.png'), optimize=True)
            items.append((iid, cols))
        entries.append((name, items))
    lines = ['-- Generated by tools/preset_icons.py from %s; do not edit. Not committed.' % folder.name,
             'return {icons={']
    for name, items in entries:
        layer_text = ','.join('{image=%s,colours={r={%d,%d,%d,%d},g={%d,%d,%d,%d},b={%d,%d,%d,%d}}}' % (
            lua_string(iid), *cols[0], *cols[1], *cols[2]) for iid, cols in items)
        lines.append('  {name=%s,layers={%s}},' % (lua_string(name), layer_text))
    lines.append('}}')
    generated.parent.mkdir(parents=True, exist_ok=True)
    generated.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    return entries, skipped


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('folder', nargs='?', help='the pictures (default: Documents\\HD2R Editor\\Preset icons)')
    parser.add_argument('--clean', action='store_true')
    parser.add_argument('--images', help=argparse.SUPPRESS)       # tests: another images/ folder
    parser.add_argument('--generated', help=argparse.SUPPRESS)    # tests: another generated file
    args = parser.parse_args(argv)
    images = Path(args.images) if args.images else PROJECT / 'images'
    generated = Path(args.generated) if args.generated else PROJECT / 'src' / 'editor' / 'generated' / 'preset_icons.lua'
    if args.clean:
        clean(images, generated)
        return 0
    folder = Path(args.folder) if args.folder else default_folder()
    if not folder.is_dir():
        print('no folder %s: put your pictures (PNG or JPG, square works best) there, or name a folder' % folder,
              file=sys.stderr)
        return 1
    entries, skipped = build(folder, images, generated)
    print('%d preset pictures -> images/%s*.png, %s' % (len(entries), PREFIX, generated))
    for name in skipped:
        print('  not a picture this tool can read: ' + name)
    return 0


if __name__ == '__main__':
    sys.exit(main())
